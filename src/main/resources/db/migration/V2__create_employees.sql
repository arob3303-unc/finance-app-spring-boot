-- V2: table for the Employee CRUD entity.

CREATE TABLE employees
(
    -- BIGINT, not INTEGER like software_engineer: Employee.id is a Java `long`,
    -- and validate checks that the column type matches the field type.
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    first_name VARCHAR(255),
    last_name  VARCHAR(255),
    email_id   VARCHAR(255),
    CONSTRAINT pk_employees PRIMARY KEY (id)
);